"""Minimal structural ports. Protocols are declarations, not delivered adapters."""
from typing import Optional, Protocol, Tuple
from .core import ClockStamp, Envelope, Owner, EvidenceRef
from .models import (ContractCheck, ConsumerContext, HealthSnapshot, BaseCommand,
                     ArmCommand, PumpCommand, ActionEvent, StopRequest, StopReport,
                     LocalizationSnapshot, MapMetadata, WaypointQuery, WaypointResult,
                     NavigationRequest, NavigationResult, PerceptionRequest, PerceptionResult,
                     ClassificationRequest, ClassificationResult, GeometryRequest, GeometryResult,
                     GraspRequest, ManipulationResult, ToolObservation, HoldingSnapshot,
                     PlacementRequest, PlacementResult, SpaceSnapshot, LayoutSnapshot,
                     StillnessCertificate, MissionInput, MissionDecision, RuntimeSignal,
                     RuntimeDecision, PermissionRequest, RecoveryRequest, RecoveryResult,
                     StateTransaction, CommitReceipt, ReadResult, ActionIntent, TimerRecord,
                     SealRequest, EndMarker, CleanupRequest, CleanupResult,
                     IntegrationRequest, IntegrationReport, IntentReceipt, HoldingUpdate, ReleaseEvent,
                     PlacementGeometryRequest, SupportGeometryRequest, SupportGeometryResult, InitializeRunRequest)


class ContractPort(Protocol):
    def check(self, envelope: Envelope, context: ConsumerContext) -> ContractCheck: ...


class ClockPort(Protocol):
    def now(self) -> ClockStamp: ...


class DevicePort(Protocol):
    def health(self) -> HealthSnapshot: ...
    def submit_base(self, command: BaseCommand) -> ActionEvent: ...
    def submit_arm(self, command: ArmCommand) -> ActionEvent: ...
    def submit_pump(self, command: PumpCommand) -> ActionEvent: ...
    def stop(self, request: StopRequest) -> StopReport: ...


class MappingPort(Protocol):
    def map_metadata(self) -> MapMetadata: ...
    def localization(self) -> LocalizationSnapshot: ...
    def query(self, request: WaypointQuery, space: SpaceSnapshot) -> WaypointResult: ...
    def record(self, waypoint: WaypointResult) -> ContractCheck: ...


class NavigationPort(Protocol):
    def navigate(self, request: NavigationRequest) -> NavigationResult: ...
    def cancel(self, request: StopRequest) -> StopReport: ...
    def invalidate_space(self, snapshot: SpaceSnapshot) -> ContractCheck: ...


class PerceptionPort(Protocol):
    def observe(self, request: PerceptionRequest) -> PerceptionResult: ...


class ClassificationPort(Protocol):
    def read_mapping(self, request: ClassificationRequest) -> ClassificationResult: ...


class GeometryPort(Protocol):
    def plan(self, request: GeometryRequest) -> GeometryResult: ...
    def plan_placement(self, request: PlacementGeometryRequest) -> GeometryResult: ...
    def support_geometry(self, request: SupportGeometryRequest) -> SupportGeometryResult: ...


class ManipulationPort(Protocol):
    def grasp(self, request: GraspRequest) -> ManipulationResult: ...
    def observe_holding(self, observation: ToolObservation) -> HoldingSnapshot: ...
    def cancel(self, request: StopRequest) -> ManipulationResult: ...
    def propose_release(self, release: ReleaseEvent, holding: HoldingSnapshot) -> HoldingUpdate: ...


class PlacementPort(Protocol):
    def place(self, request: PlacementRequest) -> PlacementResult: ...
    def propose_space(self, observations: PerceptionResult, previous: SpaceSnapshot) -> SpaceSnapshot: ...
    def assess_layout(self, snapshot: SpaceSnapshot, previous: LayoutSnapshot) -> LayoutSnapshot: ...
    def assess_stillness(self, observations: Tuple[PerceptionResult, ...],
                         stop: StopReport, snapshot: SpaceSnapshot) -> Optional[StillnessCertificate]: ...


class MissionPort(Protocol):
    def step(self, inputs: MissionInput) -> MissionDecision: ...


class RuntimePort(Protocol):
    def signal(self, signal: RuntimeSignal) -> RuntimeDecision: ...
    def request_permission(self, request: PermissionRequest) -> RuntimeDecision: ...
    def supervise(self, now: ClockStamp, health: HealthSnapshot) -> RuntimeDecision: ...
    def recover(self, result: RecoveryResult) -> RuntimeDecision: ...


class StateStorePort(Protocol):
    def commit(self, transaction: StateTransaction) -> CommitReceipt: ...
    def read(self, run_id: str) -> ReadResult: ...


class PersistencePort(StateStorePort, Protocol):
    def initialize_run(self, request: InitializeRunRequest) -> CommitReceipt: ...
    def commit_intent(self, intent: ActionIntent) -> IntentReceipt: ...
    def append_event(self, event: ActionEvent) -> CommitReceipt: ...
    def save_keyframe(self, reference: EvidenceRef, content: bytes) -> EvidenceRef: ...
    def refresh_timer(self, record: TimerRecord) -> CommitReceipt: ...
    def register_recovery(self, request: RecoveryRequest) -> RecoveryResult: ...
    def seal(self, request: SealRequest) -> EndMarker: ...
    def cleanup(self, request: CleanupRequest) -> CleanupResult: ...


class IntegrationPort(Protocol):
    def verify(self, request: IntegrationRequest) -> IntegrationReport: ...


